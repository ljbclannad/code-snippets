package com.spring.simulation.transaction;

/**
 * 事务传播行为
 *
 * 定义了当一个事务方法被另一个事务方法调用时，事务应该如何传播
 */
public enum Propagation {
    /**
     * REQUIRED（默认）
     * 如果当前存在事务，则加入该事务；如果当前没有事务，则创建一个新事务
     * 最常用的传播行为
     */
    REQUIRED,

    /**
     * REQUIRES_NEW
     * 创建一个新事务，如果当前存在事务，则挂起当前事务
     * 使用场景：日志记录、审计等需要独立提交的操作
     */
    REQUIRES_NEW,

    /**
     * NESTED
     * 如果当前存在事务，则在嵌套事务内执行；如果当前没有事务，则创建一个新事务
     * 嵌套事务可以独立回滚，但依赖外部事务的提交
     */
    NESTED,

    /**
     * SUPPORTS
     * 如果当前存在事务，则加入该事务；如果当前没有事务，则以非事务方式执行
     * 使用场景：查询操作
     */
    SUPPORTS,

    /**
     * NOT_SUPPORTED
     * 以非事务方式执行，如果当前存在事务，则挂起当前事务
     * 使用场景：不需要事务的操作
     */
    NOT_SUPPORTED,

    /**
     * MANDATORY
     * 如果当前存在事务，则加入该事务；如果当前没有事务，则抛出异常
     * 使用场景：必须在事务中执行的操作
     */
    MANDATORY,

    /**
     * NEVER
     * 以非事务方式执行，如果当前存在事务，则抛出异常
     * 使用场景：禁止在事务中执行的操作
     */
    NEVER
}
