-- 健康知识库表
CREATE TABLE IF NOT EXISTS health_knowledge (
    id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '主键ID',
    topic VARCHAR(100) NOT NULL COMMENT '主题/关键词',
    category VARCHAR(50) NOT NULL COMMENT '分类: NUTRITION-营养, EXERCISE-运动, DISEASE-疾病, MEDICATION-用药, LIFESTYLE-生活方式',
    title VARCHAR(200) NOT NULL COMMENT '标题',
    content TEXT NOT NULL COMMENT '内容',
    tags JSON COMMENT '标签（JSON数组）',
    source VARCHAR(200) COMMENT '来源',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    INDEX idx_topic (topic),
    INDEX idx_category (category),
    FULLTEXT INDEX ft_title_content (title, content)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='健康知识库表';

